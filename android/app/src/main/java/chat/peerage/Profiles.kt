package chat.peerage

import android.content.Context
import java.io.File

/**
 * Раскладка профилей на диске (ADR-015 F4, шаг беты 8.7): всё, что относится к профилю, —
 * база, блобы, ключ хранилища, `profile.json` — внутри `files/profiles/<слот>/`. Общего
 * списка профилей нет. Дополнительные профили (после беты) получат непрозрачные имена из
 * пароля; главный — постоянное `main`: что он есть, и так видно по установленному
 * приложению, а о дополнительных его имя ничего не говорит.
 *
 * Данные до раскладки не переносятся (решение владельца 2026-11-23: до раздачи беты —
 * `pm clear`). Вне профилей — только общее для приложения (файл последнего падения).
 */
object Profiles {
    /** Каталог главного профиля. */
    fun main(ctx: Context): File = File(ctx.applicationContext.filesDir, "profiles/main").apply { mkdirs() }
}
