//! Байт канала датаграммы приложения.
//!
//! Все датаграммы начинаются с 1 байта канала: [`CHAN_CHAT`] или [`CHAN_MEDIA`] —
//! это позволяет мультиплексировать надёжный чат и реалтайм-медиа по одному пути
//! Yggdrasil без отдельного сокета (инвариант 2). Байт открыт сети осознанно: по нему
//! флуд режется до расшифровки (threat model N7). Формат самих медиа-пакетов — в
//! крейте `litertc` (ADR-014).

/// Канал надёжного чата (далее — запечатанный пакет сессии).
pub const CHAN_CHAT: u8 = 0x01;
/// Канал реалтайм-медиа (далее — запечатанный медиа-пакет `litertc`).
pub const CHAN_MEDIA: u8 = 0x02;
